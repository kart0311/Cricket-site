// Live overlay for a Test in progress. Pure functions; refresh/live.mjs does the I/O.
//
// Neutral feed format (one object per delivery, in any order, the whole innings so far on every call):
//   { "asOf": "2027-01-21T07:30:00Z",
//     "balls": [ { "inn": 1, "over": 12, "ball": 3, "bowler": "Jasprit Bumrah", "batter": "Travis Head",
//                  "runs": 4, "extras": 0, "wide": false, "noball": false, "wicket": null } ] }
// "runs" is runs off the bat, "extras" is extras on that ball, "wicket" is the dismissal kind of the striker
// ("bowled", "caught", "lbw", "run out" ...) or null. Same definitions as the Cricsheet grid: wides are not balls faced,
// no-balls are; run outs are not credited to the bowler.
import { CREDITED } from './lib.mjs';

const clean = (s) => String(s || '').toLowerCase().replace(/[.']/g, '').replace(/\s+/g, ' ').trim();
const last = (s) => clean(s).split(' ').slice(-1)[0];

/** Maps a name from the feed onto a squad player: exact display name, exact Cricsheet name, then unique surname (+ initial). */
export function makeMatcher(squads) {
    const exact = new Map();
    for (const p of squads) { exact.set(clean(p.name), p); if (p.raw) exact.set(clean(p.raw), p); }
    return (name) => {
        const c = clean(name);
        if (exact.has(c)) return exact.get(c);
        let cands = squads.filter((p) => last(p.name) === last(name));
        if (cands.length > 1) { const ini = c[0]; cands = cands.filter((p) => clean(p.name)[0] === ini); }
        return cands.length === 1 ? cands[0] : null;
    };
}

export function aggregateFeed(feed, cfg, fixture) {
    const match = makeMatcher(cfg.squads);
    const cells = {}; const vcells = {}; const unknown = new Set(); let used = 0; let total = 0;
    for (const b of feed.balls || []) {
        total += 1;
        const pb = match(b.bowler); const pa = match(b.batter);
        if (!pb) unknown.add(b.bowler); if (!pa) unknown.add(b.batter);
        if (!pb || !pa || pb.team === pa.team) continue;
        used += 1;
        const key = pb.name + '|' + pa.name;
        const c = cells[key] || (cells[key] = [0, 0, 0, 0]);
        const v = vcells[fixture.venue + '|' + key] || (vcells[fixture.venue + '|' + key] = [0, 0, 0]);
        const runs = Number(b.runs) || 0; const ex = Number(b.extras) || 0;
        const out = !!b.wicket && CREDITED.has(String(b.wicket).toLowerCase());
        if (!b.wide) { c[0] += 1; c[1] += runs; if (runs + ex === 0) c[2] += 1; v[0] += 1; v[1] += runs; }
        if (out) { c[3] += 1; v[2] += 1; }
    }
    return { cells, vcells, used, total, unknown: [...unknown].filter(Boolean) };
}

export function renderLive(live) {
    return '// Generated by refresh/live.mjs while a Test is in progress. Do not edit by hand.\n' +
        'export const LIVE: any = ' + JSON.stringify(live) + ';\n';
}

/** The fixture that is on now (from a few hours before the first ball to half a day after the last), if any. */
export function activeFixture(configs, now) {
    for (const cfg of configs) for (const f of cfg.fixtures) {
        const s = Date.parse(f.start);
        if (now >= s - 3 * 3600e3 && now <= s + f.days * 864e5 + 12 * 3600e3) return { cfg, fixture: f };
    }
    return null;
}
